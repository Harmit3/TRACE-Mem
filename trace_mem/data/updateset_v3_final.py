def generate() -> list[dict]:
    rng = random.Random(SEED)
    histories = []
    for split, families in FAMILIES.items():
        for family, predicate, old_root, new_root, *turns in families:
            for place in PLACES:
                identifier = f"trace-v3-final/{split}/{family}/{place.lower()}"
                old, new = f"{old_root} in {place}", f"{new_root} in {place}"
                seed_day = date(2026, 5, 12) - timedelta(days=rng.choice((9, 18, 35, 64, 120)))
                days = [date(2026, 5, day) for day in (12, 19, 28)]
                # Budget is assigned independently of the outcome and debited only by actual calls.
                cap = rng.choice((1, 2, 3))
                old_kind = rng.choice(("direct", "dated_record", "reported"))
                histories.append({
                    "id": identifier, "split": split, "family": family, "cap": cap,
                    "prior": {"predicate": predicate, "value": old, "observed_on": seed_day.isoformat(),
                              "kind": old_kind},
                    "turns": [
                        {"date": day.isoformat(), "message": message.format(old=old, new=new),
                         "source_kind": kind,
                         "gold": {"current": old if expected == "old" else new, "prior": old}
                         if expected is not None else None}
                        for day, (message, expected, kind) in zip(days, turns)
                    ],
                })
    return histories
